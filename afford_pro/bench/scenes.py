"""Scene registry for AFFORD-Bench: free bodies with their home starts, named target points, and mechanisms.

Target points are world positions of receptacles and marked squares; the environment drops a body there at start-up
to find its resting pose, so a target only needs the right x, y and a z at which the body, held upright, is above the
receptacle floor and below any overhang. The scene XMLs are generated by scripts/build_bench_scenes.py.
"""
from __future__ import annotations

from dataclasses import dataclass, field
from typing import Mapping

from afford_pro.bench.spec import Region, Slots, Start


@dataclass(frozen=True)
class Body:
    home: Start
    # Any face up counts as upright (cubes).
    any_face_up: bool = False
    # Oracle hints: grasp yaw symmetry (rad; None for round bodies) and grasp height above the origin (m).
    grasp_symmetry: float | None = None
    grasp_height: float | None = None
    # Rotational symmetry (rad) of a part that must be turned to fit its socket; None if any yaw fits.
    yaw_symmetry: float | None = None
    # Whether start layouts must admit a top-down grasp of the whole body (False for bodies grasped by a knob).
    check_grasp: bool = True
    # Body axis that lies horizontal at rest ("y" for a cylinder lying on its side, which may roll about it);
    # None for bodies whose z axis stands up.
    lies_along: str | None = None
    # Largest height spread of the support under a start pose (m); ribbed grills need more than flat tables.
    support_spread: float = 0.002


@dataclass(frozen=True)
class Button:
    joint: str
    cap: str               # body pushed from above
    latch: float = 0.008   # pressed once the joint is pushed in this far (m); travel is 0.012 m


@dataclass(frozen=True)
class Slider:
    joint: str
    face: str                                  # body pushed to close the slider
    push_dir: tuple[float, float, float]       # world direction that closes it
    face_point: tuple[float, float, float]     # point on the pushed face, in the face body's frame
    open: float                                # joint value at the open end (the closed end is 0)
    tol: float = 0.004


@dataclass(frozen=True)
class Scene:
    xml: str
    precision: tuple[float, float]   # default goal tolerance (m) and tilt bound (deg)
    bodies: Mapping[str, Body]
    targets: Mapping[str, tuple[float, float, float]]
    buttons: Mapping[str, Button] = field(default_factory=dict)
    sliders: Mapping[str, Slider] = field(default_factory=dict)
    # Targets carried by a mechanism body (target -> body), e.g. the inside of a drawer; given with sliders open.
    attached: Mapping[str, str] = field(default_factory=dict)
    # Region targets (bins, trays, plates, marked squares): target -> (target at the region's center, inner
    # half-size in m). A body is "on" a region target when its footprint lies inside the region; the target point
    # itself is only where it is aimed, so several aim points (a bin's left and right halves) can share a region.
    regions: Mapping[str, tuple[str, float]] = field(default_factory=dict)
    # Bodies added to a task's scene as clutter, in order of preference (the first two not used by the task).
    distractors: tuple[str, ...] = ()


QUARTER = 1.5707963267948966
HALF = 2.0 * QUARTER
PRECISE, LOOSE = (0.002, 5.0), (0.008, 15.0)


def _sponge(home: Start) -> Body:
    return Body(home, grasp_symmetry=HALF)


