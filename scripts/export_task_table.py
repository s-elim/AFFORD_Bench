"""Write the task table (docs/roadmap/T9_TASK_TABLE.md and docs/roadmap/evidence/bench_tasks.json) from the task
specifications, so the documented definitions are always the ones the code runs.

    python scripts/export_task_table.py
"""
from __future__ import annotations

import json
import sys
from collections import Counter
from dataclasses import asdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from afford_pro.bench.spec import (Closed, GripperAbove, HeldOver, Lifted, On, Opened, Placed, Pressed,  # noqa: E402
                                Region, Slid, Slots, Touching, step_budget)
from afford_pro.bench.tasks import TASKS  # noqa: E402

DOMAIN_SHORT = {"Industrial & Manufacturing": "D1", "Culinary & Kitchen Operations": "D2", "Tabletop & Domestic": "D3",
                "Laboratory & Life Sciences": "D4", "Long-Horizon Multi-Stage": "D5",
                "Multi-Stage Precision Chaining": "D6", "Sequential Service & Culinary Assembly": "D7"}


def goal_text(goal) -> str:
    once = " (waypoint)" if getattr(goal, "once", False) else ""
    if isinstance(goal, On):
        tol = f", {goal.tol_xy * 1e3:.0f} mm" if goal.tol_xy else ""
        return f"on({goal.body}, {goal.target}{tol}){once}"
    if isinstance(goal, Lifted):
        return f"lifted({goal.body}, {goal.height * 100:.0f} cm)"
    if isinstance(goal, Pressed):
        return f"pressed({goal.button})"
    if isinstance(goal, (Closed, Opened)):
        return f"{type(goal).__name__.lower()}({goal.slider})"
    if isinstance(goal, GripperAbove):
        return f"gripper_above({goal.target}, {goal.height * 100:.0f} cm)"
    if isinstance(goal, Touching):
        return f"touching({goal.body}){' (event)' if goal.once else ''}"
    if isinstance(goal, HeldOver):
        return f"held_over({goal.body}, {goal.target}, {goal.clearance * 100:.0f} cm){once}"
    if isinstance(goal, Slid):
        return f"slid({goal.body}, {goal.target})"
    return repr(goal)


def start_text(start) -> str:
    if isinstance(start, Placed):
        return f"placed on {start.target}"
    if isinstance(start, Slots):
        return f"one of {', '.join(start.targets)}"
    if isinstance(start, Region):
        return f"region {start.center} +/- {start.half}"
    return repr(start)


def _cell(text: str) -> str:
    return text.replace("|", "\\|")


def table_markdown() -> str:
    kinds = Counter(type(g).__name__ for t in TASKS for g in t.goals)
    changed = sum(bool(t.change) for t in TASKS)
    lines = [
        "# T9 task table: AFFORD-Bench tasks",
        "",
        "Generated by `scripts/export_task_table.py` from `afford_pro/bench/tasks/` (do not edit by hand).",
        "",
        f"{len(TASKS)} tasks; {changed} redefined (reason given), {len(TASKS) - changed} kept with tightened "
        f"wording. Goals per task: {dict(sorted(Counter(len(t.goals) for t in TASKS).items()))}. Goal types: "
        f"{dict(kinds.most_common())}.",
        "",
        "Success = every goal holds at the same step, each goal reached no earlier than the goals ordered before it; "
        "waypoints and events must have held once. Starts other than those listed use the scene's home regions.",
        "",
        "| # | Dom | Task | Instruction | Goals | Starts | Budget | Legacy task / instruction | Change |",
        "|---|-----|---------|-------------|-------|--------|--------|------------------------|--------|",
    ]
    for t in TASKS:
        goals = "; ".join(goal_text(g) for g in t.goals)
        if t.order:
            goals += f"; order {list(t.order)}"
        starts = "; ".join(f"{b}: {start_text(s)}" for b, s in t.starts.items()) or "home"
        lines.append(f"| {t.number} | {DOMAIN_SHORT.get(t.domain, t.domain)} | `{t.task_id}` ({t.scene}) | "
                     f"{_cell(t.instruction)} | {_cell(goals)} | {_cell(starts)} | {step_budget(t)} | "
                     f"`{t.legacy_task_id}`: {_cell(t.legacy_instruction)} | {_cell(t.change or 'wording only')} |")
    return "\n".join(lines) + "\n"


def tasks_json() -> list[dict]:
    out = []
    for t in TASKS:
        out.append({"number": t.number, "task_id": t.task_id, "domain": t.domain, "scene": t.scene,
                    "instruction": t.instruction, "goals": [goal_text(g) for g in t.goals],
                    "goal_types": [type(g).__name__ for g in t.goals], "order": [list(p) for p in t.order],
                    "starts": {b: start_text(s) for b, s in t.starts.items()}, "budget": step_budget(t),
                    "legacy_task_id": t.legacy_task_id, "legacy_instruction": t.legacy_instruction, "change": t.change,
                    "spec": json.loads(json.dumps(asdict(t), default=str))})
    return out


def main() -> None:
    (ROOT / "docs" / "roadmap" / "T9_TASK_TABLE.md").write_text(table_markdown(), encoding="utf-8")
    out = ROOT / "docs" / "roadmap" / "evidence" / "bench_tasks.json"
    out.write_text(json.dumps(tasks_json(), indent=1), encoding="utf-8")
    print("wrote docs/roadmap/T9_TASK_TABLE.md and", out.relative_to(ROOT))


if __name__ == "__main__":
    main()
